        public event Action? LanguageChanged;

        private string _currentLanguage = Models.AppSettings.GetDefaultOsLanguage();

        public string CurrentLanguage
        {
            get => _currentLanguage;
            set
            {
                string normalized = Models.AppSettings.NormalizeLanguageCode(value);
                if (_currentLanguage != normalized)
                {
                    _currentLanguage = normalized;
                    LanguageChanged?.Invoke();
                    TranslateRegisteredRoots();
                }
            }
        }

        public string this[string key] => GetString(key);

        public string GetString(string key)
        {
            if (string.IsNullOrEmpty(key)) return "";

            if (_strings.TryGetValue(_currentLanguage, out var dict) && dict.TryGetValue(key, out var val))
            {
                return val;
            }

            // Fallback to Russian
            if (_strings.TryGetValue("ru", out var ruDict) && ruDict.TryGetValue(key, out var ruVal))
            {
                return ruVal;
            }

            return key;
        }

        public string FormatSize(long bytes)
        {
            if (bytes <= 0) return "-";

            double value;
            string unit;
            string lang = _currentLanguage;

            if (bytes >= 1_099_511_627_776L) // 1 TB
            {
                value = bytes / 1_099_511_627_776.0;
                unit = lang switch { "ru" => "ТБ", "fr" => "To", _ => "TB" };
            }
            else if (bytes >= 1_073_741_824L) // 1 GB
            {
                value = bytes / 1_073_741_824.0;
                unit = lang switch { "ru" => "ГБ", "fr" => "Go", _ => "GB" };
            }
            else if (bytes >= 1_048_576L) // 1 MB
            {
                value = bytes / 1_048_576.0;
                unit = lang switch { "ru" => "МБ", "fr" => "Mo", _ => "MB" };
            }
            else if (bytes >= 1024L) // 1 KB
            {
                value = bytes / 1024.0;
                unit = lang switch { "ru" => "КБ", "fr" => "Ko", _ => "KB" };
            }
            else
            {
                unit = lang switch { "ru" => "Б", "fr" => "o", _ => "B" };
                return $"{bytes} {unit}";
            }

            return $"{value:F2} {unit}";
        }

